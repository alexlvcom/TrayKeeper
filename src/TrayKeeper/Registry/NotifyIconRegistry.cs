using Microsoft.Win32;
using TrayKeeper.Logging;
using TrayKeeper.Model;

namespace TrayKeeper.Registry;

public interface INotifyIconRegistry
{
    /// <summary>Reads every notification-area entry for the current user.</summary>
    IReadOnlyList<NotifyIconEntry> Read();

    /// <summary>Writes <c>IsPromoted</c> for one entry.</summary>
    void SetPromoted(string keyName, bool promoted);

    /// <summary>Deletes <c>IsPromoted</c>, restoring the "value absent" state.</summary>
    void RemovePromoted(string keyName);

    /// <summary>Raw values for every entry, for the pre-change backup.</summary>
    IReadOnlyList<IReadOnlyDictionary<string, object?>> ReadRawForBackup();
}

/// <summary>
/// Access to <c>HKEY_CURRENT_USER\Control Panel\NotifyIconSettings</c>, the Windows 11 store
/// behind Settings &gt; Personalization &gt; Taskbar &gt; Other system tray icons.
///
/// Layout, as verified on Windows 11 build 26200:
///   Subkey name     opaque decimal 64-bit hash generated by Explorer — never synthesised here.
///   ExecutablePath  REG_SZ, optionally prefixed with a KNOWNFOLDERID in brace form.
///   IsPromoted      REG_DWORD, 1 = shown on the taskbar, 0 = in the overflow flyout.
///                   Frequently absent; absent behaves as 0.
///   UID             REG_DWORD, the NOTIFYICONDATA uID.
///   IconGuid        REG_SZ, the NOTIFYICONDATA guidItem, for GUID-identified icons.
///   InitialTooltip  REG_SZ, the tooltip captured when the icon first appeared.
///   Publisher       REG_SZ, publisher string recorded by Explorer.
///   IconSnapshot    REG_BINARY PNG — never read or written by TrayKeeper.
///
/// This class only ever writes <c>IsPromoted</c>, only under HKCU, and never creates or deletes
/// a subkey.
/// </summary>
public sealed class NotifyIconRegistry : INotifyIconRegistry
{
    internal const string SubKeyPath = @"Control Panel\NotifyIconSettings";

    private const string ValueExecutablePath = "ExecutablePath";
    private const string ValueIsPromoted = "IsPromoted";
    private const string ValueUid = "UID";
    private const string ValueIconGuid = "IconGuid";
    private const string ValueInitialTooltip = "InitialTooltip";
    private const string ValuePublisher = "Publisher";

    /// <summary>Values copied into the backup. <c>IconSnapshot</c> is excluded: it is a large
    /// PNG blob, is regenerated by Explorer, and is irrelevant to what we change.</summary>
    private static readonly string[] BackupValueNames =
    {
        ValueExecutablePath, ValueIsPromoted, ValueUid, ValueIconGuid, ValueInitialTooltip, ValuePublisher,
    };

    private readonly IKnownFolderResolver _knownFolders;
    private readonly IFileIdentityProvider _fileIdentities;
    private readonly ILog _log;

    public NotifyIconRegistry(IKnownFolderResolver knownFolders, IFileIdentityProvider fileIdentities, ILog log)
    {
        _knownFolders = knownFolders;
        _fileIdentities = fileIdentities;
        _log = log;
    }

    public IReadOnlyList<NotifyIconEntry> Read()
    {
        var entries = new List<NotifyIconEntry>();

        using var root = Microsoft.Win32.Registry.CurrentUser.OpenSubKey(SubKeyPath, writable: false);
        if (root is null)
        {
            _log.Warn($@"Registry key HKCU\{SubKeyPath} was not found. This build of Windows may store " +
                      "notification-area settings elsewhere.");
            return entries;
        }

        foreach (var keyName in root.GetSubKeyNames())
        {
            try
            {
                using var subKey = root.OpenSubKey(keyName, writable: false);
                if (subKey is null) continue;

                var entry = ReadEntry(keyName, subKey);
                if (entry is not null) entries.Add(entry);
            }
            catch (Exception ex) when (ex is System.Security.SecurityException or UnauthorizedAccessException or IOException)
            {
                _log.Warn($"Skipped notification-area entry {keyName}: {ex.Message}");
            }
        }

        return entries;
    }

    private NotifyIconEntry? ReadEntry(string keyName, RegistryKey subKey)
    {
        var raw = subKey.GetValue(ValueExecutablePath) as string;
        if (string.IsNullOrWhiteSpace(raw))
        {
            _log.Debug($"Entry {keyName} has no usable ExecutablePath; ignored.");
            return null;
        }

        var (resolvedPath, hadPrefix, resolved) = ExecutablePathResolver.Resolve(raw, _knownFolders);
        if (hadPrefix && !resolved)
        {
            _log.Debug($"Entry {keyName}: known-folder prefix in '{raw}' could not be expanded.");
        }

        return new NotifyIconEntry
        {
            KeyName = keyName,
            RawExecutablePath = raw,
            ResolvedExecutablePath = resolvedPath,
            IsPromoted = ReadFlag(subKey, keyName),
            Uid = ReadUint(subKey, ValueUid),
            IconGuid = subKey.GetValue(ValueIconGuid) as string,
            InitialTooltip = subKey.GetValue(ValueInitialTooltip) as string,
            Publisher = subKey.GetValue(ValuePublisher) as string,
            File = _fileIdentities.Get(resolvedPath),
        };
    }

    private bool? ReadFlag(RegistryKey subKey, string keyName)
    {
        var value = subKey.GetValue(ValueIsPromoted);
        if (value is null) return null;

        try
        {
            return Convert.ToInt64(value) != 0;
        }
        catch (Exception ex) when (ex is FormatException or InvalidCastException or OverflowException)
        {
            _log.Warn($"Entry {keyName}: IsPromoted has unexpected type {value.GetType().Name}; treated as absent.");
            return null;
        }
    }

    private static uint? ReadUint(RegistryKey subKey, string valueName)
    {
        var value = subKey.GetValue(valueName);
        if (value is null) return null;

        try
        {
            var asLong = Convert.ToInt64(value);
            return asLong is >= uint.MinValue and <= uint.MaxValue ? (uint)asLong : null;
        }
        catch (Exception ex) when (ex is FormatException or InvalidCastException or OverflowException)
        {
            return null;
        }
    }

    public void SetPromoted(string keyName, bool promoted)
    {
        using var subKey = OpenForWrite(keyName);
        subKey.SetValue(ValueIsPromoted, promoted ? 1 : 0, RegistryValueKind.DWord);
        _log.Info($"Set IsPromoted={(promoted ? 1 : 0)} on entry {keyName}.");
    }

    public void RemovePromoted(string keyName)
    {
        using var subKey = OpenForWrite(keyName);
        subKey.DeleteValue(ValueIsPromoted, throwOnMissingValue: false);
        _log.Info($"Removed IsPromoted from entry {keyName}.");
    }

    private static RegistryKey OpenForWrite(string keyName)
    {
        // Opening the existing subkey (rather than CreateSubKey) guarantees we never invent an
        // entry that Explorer did not create.
        var subKey = Microsoft.Win32.Registry.CurrentUser.OpenSubKey($@"{SubKeyPath}\{keyName}", writable: true);
        return subKey ?? throw new InvalidOperationException(
            $@"Notification-area entry HKCU\{SubKeyPath}\{keyName} no longer exists.");
    }

    public IReadOnlyList<IReadOnlyDictionary<string, object?>> ReadRawForBackup()
    {
        var snapshot = new List<IReadOnlyDictionary<string, object?>>();

        using var root = Microsoft.Win32.Registry.CurrentUser.OpenSubKey(SubKeyPath, writable: false);
        if (root is null) return snapshot;

        foreach (var keyName in root.GetSubKeyNames())
        {
            try
            {
                using var subKey = root.OpenSubKey(keyName, writable: false);
                if (subKey is null) continue;

                var values = new Dictionary<string, object?>(StringComparer.Ordinal) { ["Key"] = keyName };

                foreach (var name in BackupValueNames)
                {
                    var value = subKey.GetValue(name);
                    if (value is not null) values[name] = value;
                }

                snapshot.Add(values);
            }
            catch (Exception ex) when (ex is System.Security.SecurityException or UnauthorizedAccessException or IOException)
            {
                _log.Warn($"Backup skipped entry {keyName}: {ex.Message}");
            }
        }

        return snapshot;
    }
}
